#pragma once

namespace tim
{

/**
 * Уровни важности для системы логирования tim::tracef / TIM_TRACE.
 *
 * Чем выше в списке, тем серьёзнее событие. Fatal вызывает std::abort()
 * в vtracef; остальные просто пишутся в stderr.
 */
enum class severity
{
    fatal,    ///< Фатальная ошибка; процесс не может продолжать работу.
    error,    ///< Ошибка, операция не выполнена.
    warning,  ///< Подозрительная ситуация, но работа продолжается.
    info,     ///< Информационное сообщение для оператора.
    debug,    ///< Отладочное сообщение, обычно отключено в release.
    trace     ///< Самый подробный уровень: трассировка вызовов и аргументов.
};

/**
 * Короткое отображаемое имя уровня в квадратных скобках:
 * "[F]" для fatal, "[E]" для error, "[W]" для warning, "[I]" для info,
 * "[D]" для debug, "[T]" для trace.
 *
 * \param severity Уровень важности.
 * \return Указатель на статическую строку с буквенным маркером, либо
 *         nullptr для неизвестного значения.
 */
const char *severity_title(tim::severity severity);

}
